export function setupLanguage() {
  let lang;
  try {
    lang = localStorage.getItem("par-language") || "hr";
  } catch {
    lang = "hr";
  }
  const placeholders = new WeakMap();
  const originals = new WeakMap(),
    last = new WeakMap();
  const control = document.createElement("button");
  control.className = "button language-toggle";
  control.type = "button";
  control.id = "language-toggle";
  const host = document.getElementById("theme")?.parentElement || document.body;
  host.append(control);
  const observer = new MutationObserver(translate);
  function translate() {
    observer.disconnect();
    document.documentElement.lang = lang;
    control.textContent = lang === "hr" ? "EN" : "HR";
    control.setAttribute(
      "aria-label",
      lang === "hr"
        ? "Switch interface to English"
        : "Prebaci sučelje na hrvatski",
    );
    document.querySelectorAll("input[placeholder]").forEach((input) => {
      if (!placeholders.has(input))
        placeholders.set(input, input.getAttribute("placeholder"));
      const original = placeholders.get(input);
      input.setAttribute(
        "placeholder",
        lang === "en" ? words[original] || original : original,
      );
    });
    const walker = document.createTreeWalker(
      document.body,
      NodeFilter.SHOW_TEXT,
    );
    while (walker.nextNode()) {
      const node = walker.currentNode,
        parent = node.parentElement;
      if (!parent || parent.closest("script,style,textarea,#language-toggle"))
        continue;
      if (!originals.has(node) || node.textContent !== last.get(node))
        originals.set(node, node.textContent);
      const original = originals.get(node),
        trimmed = original.trim(),
        translation =
          words[trimmed] ||
          (/^Filtri \(\d+\)$/.test(trimmed)
            ? trimmed.replace("Filtri", "Filters")
            : null) ||
          (trimmed === trimmed.toUpperCase()
            ? words[trimmed[0] + trimmed.slice(1).toLowerCase()]?.toUpperCase()
            : null);
      const value =
        lang === "en" && translation
          ? original.replace(trimmed, translation)
          : original;
      if (node.textContent !== value) node.textContent = value;
      last.set(node, value);
    }
    document.querySelectorAll("[data-calendar-day]").forEach((el) => {
      const date = new Date(el.dataset.calendarDay + "T12:00:00Z");
      const format = {
        weekday: el.dataset.calendarFormat === "long" ? "long" : "short",
        day: "numeric",
        month: "numeric",
        timeZone: "Europe/Zagreb",
        ...(el.dataset.calendarFormat === "long" ? { year: "numeric" } : {}),
      };
      const text = date.toLocaleDateString(
        lang === "en" ? "en-GB" : "hr-HR",
        format,
      );
      if (el.textContent !== text) el.textContent = text;
    });
    document.querySelectorAll("[data-calendar-month]").forEach((el) => {
      const text = new Date(
        el.dataset.calendarMonth + "-01T12:00:00Z",
      ).toLocaleDateString(lang === "en" ? "en-GB" : "hr-HR", {
        month: "long",
        year: "numeric",
        timeZone: "Europe/Zagreb",
      });
      if (el.textContent !== text) el.textContent = text;
    });
    observer.observe(document.body, {
      childList: true,
      subtree: true,
      characterData: true,
    });
  }
  control.addEventListener("click", () => {
    lang = lang === "hr" ? "en" : "hr";
    try {
      localStorage.setItem("par-language", lang);
    } catch {}
    translate();
  });
  translate();
}
